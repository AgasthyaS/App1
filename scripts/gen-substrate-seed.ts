/**
 * Writes supabase/seed/substrates.sql from the app's substrate library, so the
 * database's reference tables and the app can never disagree.
 *
 *   npm run gen:substrates
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';

import { MODEL_VERSION } from '../lib/modelVersion';
import { COMPONENTS, PRESETS, resolveSubstrate } from '../lib/substrate';

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const n = (v: number) => (Number.isFinite(v) ? String(Math.round(v * 1e5) / 1e5) : 'null');
const j = (v: unknown) => (v == null ? 'null' : `${q(JSON.stringify(v))}::jsonb`);
const r3 = (x: number) => Math.round(x * 1000) / 1000;

const lines: string[] = [
  '-- GENERATED by scripts/gen-substrate-seed.ts from lib/substrate — do not edit by hand.',
  '-- Run after supabase/migrations/20261112000000_platform.sql. Safe to re-run.',
  `-- model version ${MODEL_VERSION}`,
  '',
  'insert into public.substrate_components',
  '  (id, label, family, packing_role, total_porosity, interparticle_void, spread, vg_alpha, vg_n, vg_theta_s, vg_theta_r, tier, source, note)',
  'values',
  COMPONENTS.map((c) =>
    `  (${q(c.id)}, ${q(c.label)}, ${q(c.family)}, ${q(c.role)}, ${n(c.totalPorosity)}, ${n(c.interparticleVoid)}, ${n(c.spread)}, ${n(c.vg.alpha)}, ${n(c.vg.n)}, ${n(c.vg.thetaS)}, ${n(c.vg.thetaR)}, ${q(c.tier)}, ${q(c.source)}, ${q(c.note)})`,
  ).join(',\n'),
  'on conflict (id) do update set',
  '  label = excluded.label, family = excluded.family, packing_role = excluded.packing_role,',
  '  total_porosity = excluded.total_porosity, interparticle_void = excluded.interparticle_void,',
  '  spread = excluded.spread, vg_alpha = excluded.vg_alpha, vg_n = excluded.vg_n,',
  '  vg_theta_s = excluded.vg_theta_s, vg_theta_r = excluded.vg_theta_r,',
  '  tier = excluded.tier, source = excluded.source, note = excluded.note;',
  '',
  'insert into public.substrate_presets (id, label, preset_group, substrate_key, components, properties, model_version)',
  'values',
  PRESETS.map((p) => {
    const r = resolveSubstrate({ kind: 'preset', id: p.id });
    const props = r.properties && {
      totalPorosity: mapRange(r.properties.totalPorosity),
      containerCapacity: mapRange(r.properties.containerCapacity),
      airSpace: mapRange(r.properties.airSpace),
      easilyAvailable: mapRange(r.properties.easilyAvailable),
      basis: r.properties.basis,
      weakestInput: r.properties.weakestInput,
      regime: r.properties.regime,
      vg: { alpha: r3(r.vg.alpha), n: r3(r.vg.n), thetaS: r3(r.vg.thetaS), thetaR: r3(r.vg.thetaR) },
    };
    const parts = r.parts.map((x) => ({ component: x.component, fraction: r3(x.fraction) }));
    return `  (${q(p.id)}, ${q(p.label)}, ${q(p.group)}, ${q(r.key)}, ${j(parts)}, ${j(props || { vg: r.vg, basis: 'published-anchors' })}, ${q(MODEL_VERSION)})`;
  }).join(',\n'),
  'on conflict (id) do update set',
  '  label = excluded.label, preset_group = excluded.preset_group, substrate_key = excluded.substrate_key,',
  '  components = excluded.components, properties = excluded.properties, model_version = excluded.model_version;',
  '',
];

function mapRange(x: { low: number; mid: number; high: number }) {
  return { low: r3(x.low), mid: r3(x.mid), high: r3(x.high) };
}

const out = path.resolve(__dirname, '../supabase/seed/substrates.sql');
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}: ${COMPONENTS.length} components, ${PRESETS.length} presets`);
