import { describe, expect, it } from 'vitest';

import { containerThresholds, perchedWaterTableCm, probeReads, waterContentAt } from '@/lib/soilProfile';
import {
  COMPONENTS, LEGACY_VG, MINERAL_TEXTURE_IDS, PRESETS, PRESET_FOR_LEGACY,
  componentById, fitVg, legacyClassFor, mixtureKey, mixtureProperties, normaliseParts,
  resolveSubstrate, vgTheta, type MixturePart, type SubstrateSpec,
} from '@/lib/substrate';
import type { SoilMix } from '@/lib/types';

const mix = (...p: [string, number][]): MixturePart[] => p.map(([component, parts]) => ({ component, parts }));
const PSIS = [0, 1, 2, 5, 10, 25, 50, 100, 330, 1000, 15000, 1e6];

describe('van Genuchten curve', () => {
  it('equals θs at zero suction and tends to θr', () => {
    for (const c of COMPONENTS) {
      expect(vgTheta(c.vg, 0)).toBeCloseTo(c.vg.thetaS, 10);
      // Clays (n ≈ 1.09) approach θr extremely slowly, hence the absurd suction.
      expect(vgTheta(c.vg, 1e80)).toBeCloseTo(c.vg.thetaR, 2);
    }
  });

  it('never rises with suction and stays inside [θr, θs]', () => {
    for (const c of COMPONENTS) {
      let prev = Infinity;
      for (const psi of PSIS) {
        const t = vgTheta(c.vg, psi);
        expect(t).toBeLessThanOrEqual(prev + 1e-12);
        expect(t).toBeGreaterThanOrEqual(c.vg.thetaR - 1e-12);
        expect(t).toBeLessThanOrEqual(c.vg.thetaS + 1e-12);
        prev = t;
      }
    }
  });

  it('is total: negative, NaN and infinite suction do not produce NaN', () => {
    const vg = LEGACY_VG['Standard mix'];
    for (const psi of [-5, NaN, Infinity, -Infinity]) expect(Number.isFinite(vgTheta(vg, psi))).toBe(true);
  });

  it('fitVg recovers known parameters from points generated by them', () => {
    const truth = { alpha: 0.08, n: 1.7, thetaS: 0.6, thetaR: 0.1 };
    const pts = [2, 5, 10, 20, 50, 100, 500, 5000].map((psi) => ({ psi, theta: vgTheta(truth, psi) }));
    const { vg, rmse } = fitVg(pts, truth.thetaS, truth.thetaR);
    expect(rmse).toBeLessThan(0.002);
    expect(vg.alpha).toBeCloseTo(truth.alpha, 2);
    expect(vg.n).toBeCloseTo(truth.n, 1);
  });

  it('fitVg tolerates empty and degenerate input', () => {
    expect(Number.isFinite(fitVg([], 0.8, 0.1).vg.alpha)).toBe(true);
    expect(Number.isFinite(fitVg([{ psi: NaN, theta: 0.3 }], 0.8, 0.9).vg.n)).toBe(true);
  });
});

describe('mineral textures (Carsel & Parrish 1988)', () => {
  it('has all twelve USDA classes with the published values', () => {
    expect(MINERAL_TEXTURE_IDS).toHaveLength(12);
    expect(componentById('sand')!.vg).toEqual({ alpha: 0.145, n: 2.68, thetaS: 0.43, thetaR: 0.045 });
    expect(componentById('loam')!.vg).toEqual({ alpha: 0.036, n: 1.56, thetaS: 0.43, thetaR: 0.078 });
    expect(componentById('clay')!.vg).toEqual({ alpha: 0.008, n: 1.09, thetaS: 0.38, thetaR: 0.068 });
  });

  it('sand gives up its water at low suction; clay holds nearly all of it', () => {
    const released = (id: string) => {
      const vg = componentById(id)!.vg;
      return (vg.thetaS - vgTheta(vg, 50)) / (vg.thetaS - vg.thetaR);
    };
    expect(released('sand')).toBeGreaterThan(0.9);
    expect(released('loam')).toBeGreaterThan(0.25);
    expect(released('clay')).toBeLessThan(0.05);
  });

  it('garden soil in a pot has almost no air at container capacity', () => {
    // The reason "don't use garden soil in pots" is true: a pot is too short to
    // pull a fine soil's pores open.
    for (const id of ['loam', 'clay-loam', 'silt-loam', 'clay']) {
      const vg = componentById(id)!.vg;
      expect(vg.thetaS - vgTheta(vg, 10)).toBeLessThan(0.05);
    }
  });
});

describe('blend model against published container measurements', () => {
  // University of Arkansas Greenhouse Management, Unit 7, 4-inch containers.
  // Peat and coir anchors were chosen using the first two rows, so those two are
  // a consistency check; the third row was not used in fitting anything.
  const cases: [string, MixturePart[], { tp: number; water: number; air: number }][] = [
    ['80:20 peat–perlite', mix(['peat', 80], ['perlite', 20]), { tp: 0.79, water: 0.68, air: 0.10 }],
    ['80:20 coir–perlite', mix(['coir', 80], ['perlite', 20]), { tp: 0.81, water: 0.73, air: 0.08 }],
    ['50:50 coir–pine bark', mix(['coir', 50], ['pine-bark', 50]), { tp: 0.78, water: 0.65, air: 0.13 }],
  ];
  for (const [name, parts, pub] of cases) {
    it(`${name} within 0.05 v/v`, () => {
      const p = mixtureProperties(parts)!;
      // A 4-inch container's capacity is the column mean, ≈ θ at 5 cm of suction.
      const water = vgTheta(p.vg, 5);
      expect(Math.abs(p.totalPorosity.mid - pub.tp)).toBeLessThan(0.055);
      expect(Math.abs(water - pub.water)).toBeLessThan(0.05);
      expect(Math.abs(p.totalPorosity.mid - water - pub.air)).toBeLessThan(0.05);
    });
  }
});

describe('blends are not linear averages', () => {
  const peat = mixtureProperties(mix(['peat', 100]))!;
  const perlite = mixtureProperties(mix(['perlite', 100]))!;

  it('a 50:50 blend holds less air than the average of its ingredients', () => {
    const blend = mixtureProperties(mix(['peat', 50], ['perlite', 50]))!;
    const linear = (peat.airSpace.mid + perlite.airSpace.mid) / 2;
    expect(blend.airSpace.mid).toBeLessThan(linear - 0.03);
    expect(blend.shrinkage.mid).toBeGreaterThan(0.05);
  });

  it('aeration barely moves below the threshold proportion, then climbs', () => {
    const air = (perlitePct: number) =>
      mixtureProperties(mix(['peat', 100 - perlitePct], ['perlite', perlitePct]))!.airSpace.mid;
    expect(Math.abs(air(30) - air(10))).toBeLessThan(0.03);
    expect(air(90) - air(60)).toBeGreaterThan(0.08);
  });

  it('reports the regime and the threshold (≈ 71% for perlite)', () => {
    const low = mixtureProperties(mix(['peat', 70], ['perlite', 30]))!;
    const high = mixtureProperties(mix(['peat', 15], ['perlite', 85]))!;
    expect(low.regime).toBe('matrix-held');
    expect(high.regime).toBe('skeleton-held');
    expect(low.thresholdCoarseFraction).toBeCloseTo(1 / 1.4, 3);
    expect(low.notes.join(' ')).toMatch(/gaps between the coarse particles/);
  });

  it('ranges are ordered, physical, and wider for a blend than for one ingredient', () => {
    const recipes = [
      mix(['potting-mix', 50], ['perlite', 30], ['coir', 20]),
      mix(['peat', 40], ['vermiculite', 30], ['perlite', 30]),
      mix(['orchid-bark', 70], ['sphagnum-moss', 15], ['perlite', 15]),
      mix(['loam', 60], ['compost', 20], ['grit', 20]),
      mix(['grit', 50], ['pumice', 30], ['potting-mix', 20]),
    ];
    for (const r of recipes) {
      const p = mixtureProperties(r)!;
      for (const key of ['totalPorosity', 'containerCapacity', 'airSpace', 'easilyAvailable', 'buffer'] as const) {
        const { low, mid, high } = p[key];
        expect(low).toBeGreaterThanOrEqual(0);
        expect(high).toBeLessThanOrEqual(1);
        expect(low).toBeLessThanOrEqual(mid + 1e-9);
        expect(mid).toBeLessThanOrEqual(high + 1e-9);
      }
      expect(p.containerCapacity.mid).toBeLessThanOrEqual(p.totalPorosity.mid + 1e-9);
      expect(p.basis).toBe('estimated-mixture');
    }
    const one = mixtureProperties(mix(['peat', 100]))!;
    const two = mixtureProperties(mix(['peat', 50], ['perlite', 50]))!;
    expect(two.airSpace.high - two.airSpace.low).toBeGreaterThan(one.airSpace.high - one.airSpace.low);
  });

  it('more of a water-holding ingredient means more water held', () => {
    const cc = (vermiculite: number) =>
      mixtureProperties(mix(['perlite', 100 - vermiculite], ['vermiculite', vermiculite]))!.containerCapacity.mid;
    expect(cc(60)).toBeGreaterThan(cc(20));
  });
});

describe('input handling', () => {
  it('ignores invalid parts and unknown ingredients, and merges duplicates', () => {
    const n = normaliseParts([
      { component: 'peat', parts: 2 }, { component: 'peat', parts: 2 },
      { component: 'perlite', parts: NaN }, { component: 'coir', parts: -1 },
      { component: 'unobtainium', parts: 5 }, { component: 'perlite', parts: 4 },
    ]);
    expect(n).toHaveLength(2);
    expect(n.reduce((s, p) => s + p.fraction, 0)).toBeCloseTo(1, 10);
    expect(n.find((p) => p.component === 'peat')!.fraction).toBeCloseTo(0.5, 10);
  });

  it('returns null for nothing usable, and never NaN otherwise', () => {
    expect(mixtureProperties([])).toBeNull();
    expect(mixtureProperties(null)).toBeNull();
    expect(mixtureProperties([{ component: 'peat', parts: 0 }])).toBeNull();
    const p = mixtureProperties(mix(['peat', 1e-9], ['perlite', 1e9]))!;
    expect(Object.values(p.vg).every(Number.isFinite)).toBe(true);
  });

  it('the key is order- and scale-independent', () => {
    expect(mixtureKey(mix(['peat', 1], ['perlite', 1]))).toBe(mixtureKey(mix(['perlite', 50], ['peat', 50])));
  });
});

describe('resolving a plant’s substrate', () => {
  it('a plant with no substrate keeps exactly the curve it always had', () => {
    for (const m of Object.keys(LEGACY_VG) as SoilMix[]) {
      expect(resolveSubstrate(null, m).vg).toBe(LEGACY_VG[m]);
      expect(resolveSubstrate({ kind: 'preset', id: PRESET_FOR_LEGACY[m] }).vg).toBe(LEGACY_VG[m]);
      for (const h of [8, 16, 30]) {
        const before = containerThresholds({ potHeightCm: h, soilMix: m });
        const after = containerThresholds({ potHeightCm: h, soilMix: m, substrate: { kind: 'preset', id: PRESET_FOR_LEGACY[m] } });
        expect(after).toEqual(before);
      }
    }
  });

  it('unknown is a real state: assumed potting mix, flagged as unknown', () => {
    const r = resolveSubstrate({ kind: 'unknown' });
    expect(r.knowledge).toBe('unknown');
    expect(r.vg).toBe(LEGACY_VG['Standard mix']);
    expect(resolveSubstrate(undefined, undefined).knowledge).toBe('unknown');
    expect(resolveSubstrate(null, 'bogus' as SoilMix).knowledge).toBe('unknown');
  });

  it('a broken spec falls back instead of throwing', () => {
    expect(resolveSubstrate({ kind: 'preset', id: 'nope' }, 'Chunky / aroid').vg).toBe(LEGACY_VG['Chunky / aroid']);
    expect(resolveSubstrate({ kind: 'custom', parts: [] }, 'Dense / heavy').vg).toBe(LEGACY_VG['Dense / heavy']);
    expect(() => resolveSubstrate({ kind: 'custom', parts: [{ component: 'x', parts: 1 }] } as SubstrateSpec)).not.toThrow();
  });

  it('every preset resolves to a finite curve and a legacy class', () => {
    for (const p of PRESETS) {
      const r = resolveSubstrate({ kind: 'preset', id: p.id });
      expect(Object.values(r.vg).every(Number.isFinite), p.id).toBe(true);
      expect(Object.keys(LEGACY_VG)).toContain(r.legacyClass);
      expect(r.key).toBe(`preset:${p.id}`);
    }
  });

  it('the legacy classifier maps the four original curves to themselves', () => {
    for (const m of Object.keys(LEGACY_VG) as SoilMix[]) expect(legacyClassFor(LEGACY_VG[m])).toBe(m);
  });
});

describe('the same pot reads differently in different substrates (simulated)', () => {
  const pot = (substrate: SubstrateSpec) => ({ potHeightCm: 16, soilMix: 'Standard mix' as SoilMix, substrate });
  const preset = (id: string): SubstrateSpec => ({ kind: 'preset', id });
  const custom = (...p: [string, number][]): SubstrateSpec => ({ kind: 'custom', parts: mix(...p) });

  const scenarios: [string, SubstrateSpec][] = [
    ['sandy soil', preset('sandy-soil')],
    ['loamy soil', preset('loamy-soil')],
    ['clay-heavy soil', preset('clay-soil')],
    ['peat-based potting mix', preset('potting-mix')],
    ['coco coir', preset('coco-coir')],
    ['perlite-heavy mix', custom(['peat', 30], ['perlite', 70])],
    ['vermiculite seed mix', preset('seed-mix')],
    ['orchid bark mix', preset('orchid-mix')],
    ['succulent mix', preset('succulent-mix')],
    ['custom 50/30/20', custom(['potting-mix', 50], ['perlite', 30], ['coir', 20])],
    ['unknown', { kind: 'unknown' }],
  ];

  it('every scenario yields usable, ordered thresholds', () => {
    for (const [name, s] of scenarios) {
      const th = containerThresholds(pot(s));
      expect(Number.isFinite(th.capacityReading), name).toBe(true);
      expect(th.capacityReading, name).toBeGreaterThanOrEqual(th.refillReading - 1e-6);
      expect(th.refillReading, name).toBeGreaterThanOrEqual(th.stressReading - 1e-6);
      expect(th.capacityReading, name).toBeLessThanOrEqual(100);
      expect(th.stressReading, name).toBeGreaterThanOrEqual(0);
    }
  });

  it('a just-drained pot reads far wetter in coir than in orchid bark or succulent mix', () => {
    const full = (s: SubstrateSpec) => probeReads(pot(s), 0);
    expect(full(preset('coco-coir'))).toBeGreaterThan(full(preset('orchid-mix')) + 15);
    expect(full(preset('potting-mix'))).toBeGreaterThan(full(preset('succulent-mix')) + 15);
  });

  it('the saturated layer at the base is taller in fine material than in coarse', () => {
    const pwt = (s: SubstrateSpec) => perchedWaterTableCm('Standard mix', null, s);
    expect(pwt(preset('clay-soil'))).toBeGreaterThan(pwt(preset('potting-mix')));
    expect(pwt(preset('potting-mix'))).toBeGreaterThan(pwt(preset('orchid-mix')));
  });

  it('a reading of 35 means "fine" in bark and "needs water" in coir', () => {
    const bark = containerThresholds(pot(preset('orchid-mix')));
    const coir = containerThresholds(pot(preset('coco-coir')));
    expect(35).toBeGreaterThan(bark.refillReading);
    expect(35).toBeLessThan(coir.refillReading);
  });

  it('adding perlite to potting mix lowers what "full" reads, monotonically', () => {
    const full = (pct: number) =>
      probeReads(pot(custom(['potting-mix', 100 - pct], ['perlite', pct])), 0);
    expect(full(0)).toBeGreaterThan(full(30));
    expect(full(30)).toBeGreaterThan(full(60));
    expect(full(60)).toBeGreaterThan(full(90));
  });

  it('water content is finite for every substrate at every suction', () => {
    for (const [name, s] of scenarios)
      for (const psi of PSIS) expect(Number.isFinite(waterContentAt(psi, 'Standard mix', null, s)), `${name} @ ${psi}`).toBe(true);
  });
});
